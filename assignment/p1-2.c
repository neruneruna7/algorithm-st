#include <stdio.h>

int main(void) {
    long long r[14];

    /*
        1番地に n を保存する。
        RAM課題では r1 に n が与えられる想定だが，
        Cでは標準入力から読み込んで r[1] に入れる。
    */
    scanf("%lld", &r[1]);

    /*
        2番地には 0 を保存する。
        ここでは実際には参照しない。
    */
    r[2] = 0;

    /*
        a = 0
    */
    r[3] = 0;

loop_a:
    /*
        a^2 を計算して r[4] に保存する。
    */
    r[4] = r[3] * r[3];

    /*
        a^2 > n なら探索終了。
        RAMで言えば，
            LOAD 4
            SUB 1
            JGTZ end
        に対応する。
    */
    if (r[4] > r[1]) {
        return 1;
    }

    /*
        r[5] = n - a^2
    */
    r[5] = r[1] - r[4];

    /*
        b = a
        順序を a <= b <= c <= d に固定して探索数を減らす。
        完全な総当たりにしたい場合は r[6] = 0 にする。
    */
    r[6] = r[3];

loop_b:
    /*
        b^2 を計算して r[7] に保存する。
    */
    r[7] = r[6] * r[6];

    /*
        b^2 > n - a^2 なら，現在の a に対する b の探索を終了。
    */
    if (r[7] > r[5]) {
        goto next_a;
    }

    /*
        r[8] = n - a^2 - b^2
    */
    r[8] = r[5] - r[7];

    /*
        c = b
    */
    r[9] = r[6];

loop_c:
    /*
        c^2 を計算して r[10] に保存する。
    */
    r[10] = r[9] * r[9];

    /*
        c^2 > n - a^2 - b^2 なら，
        現在の a, b に対する c の探索を終了。
    */
    if (r[10] > r[8]) {
        goto next_b;
    }

    /*
        r[11] = n - a^2 - b^2 - c^2
    */
    r[11] = r[8] - r[10];

    /*
        d = c
    */
    r[12] = r[9];

loop_d:
    /*
        d^2 を計算して r[13] に保存する。
    */
    r[13] = r[12] * r[12];

    /*
        d^2 > n - a^2 - b^2 - c^2 なら，
        現在の a, b, c に対する d の探索を終了。
    */
    if (r[13] > r[11]) {
        goto next_c;
    }

    /*
        r[11] - r[13] == 0 なら，
        n - a^2 - b^2 - c^2 - d^2 == 0
        なので解が見つかった。
    */
    if (r[11] - r[13] == 0) {
        printf("%lld\n", r[3]);   /* a */
        printf("%lld\n", r[6]);   /* b */
        printf("%lld\n", r[9]);   /* c */
        printf("%lld\n", r[12]);  /* d */
        return 0;
    }

    /*
        d++
    */
    r[12] = r[12] + 1;
    goto loop_d;

next_c:
    /*
        c++
    */
    r[9] = r[9] + 1;
    goto loop_c;

next_b:
    /*
        b++
    */
    r[6] = r[6] + 1;
    goto loop_b;

next_a:
    /*
        a++
    */
    r[3] = r[3] + 1;
    goto loop_a;
}